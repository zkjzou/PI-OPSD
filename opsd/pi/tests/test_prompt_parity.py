def test_online_config_has_one_analyzer_max_tokens_defaulting_to_32000(monkeypatch):
    from opsd.pi.online import OnlineHintConfig, online_hint_cfg_from_env

    tree = ast.parse((_PI_DIR / "online.py").read_text())
    cls = next(n for n in tree.body if isinstance(n, ast.ClassDef) and n.name == "OnlineHintConfig")
    fields = [n.target.id for n in cls.body if isinstance(n, ast.AnnAssign)]
    assert sorted({f for f in fields if fields.count(f) > 1}) == [], "duplicate OnlineHintConfig fields"
    reads = [
        n for n in ast.walk(tree) if isinstance(n, ast.Constant) and n.value == "OPSD_ONLINE_HINTS_ANALYZER_MAX_TOKENS"
    ]
    assert len(reads) == 1, "OPSD_ONLINE_HINTS_ANALYZER_MAX_TOKENS must be read exactly once"

    assert OnlineHintConfig().analyzer_max_tokens == 32000
    monkeypatch.delenv("OPSD_ONLINE_HINTS_ANALYZER_MAX_TOKENS", raising=False)
    assert online_hint_cfg_from_env().analyzer_max_tokens == 32000


def test_online_max_input_tokens_zero_survives_env_parsing(monkeypatch):
    """0 selects the legacy render; `int(x) or 32000` would silently turn it back into 32000."""
    from opsd.pi.online import online_hint_cfg_from_env

    monkeypatch.delenv("OPSD_ONLINE_HINTS_MAX_INPUT_TOKENS", raising=False)
    assert online_hint_cfg_from_env().max_input_tokens == 32000
    monkeypatch.setenv("OPSD_ONLINE_HINTS_MAX_INPUT_TOKENS", "0")
    cfg = online_hint_cfg_from_env()
    assert cfg.max_input_tokens == 0
    assert cfg.constructor_kwargs()["max_input_tokens"] == 0


