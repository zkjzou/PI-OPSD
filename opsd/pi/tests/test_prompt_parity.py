def _leaves(prefix, v, out):
    if isinstance(v, str):
        out[prefix] = _md5(v)
    elif isinstance(v, dict):
        for k, vv in v.items():
            _leaves(f"{prefix}[{k!r}]", vv, out)
    elif isinstance(v, (tuple, list)):
        for i, vv in enumerate(v):
            _leaves(f"{prefix}[{i}]", vv, out)


def _constant_table(m):
    out = {}
    for k, v in vars(m).items():
        if k.startswith("__") or not isinstance(v, (str, dict, tuple, list)):
            continue
        _leaves(k, v, out)
    return out


def _rendered_table(m, monkeypatch):
    """Same keys/recipe as the generator that produced the golden tables."""
    out = {}
    for fn in (
        "skill_system",
        "contrastive_system",
        "skill_update_system",
        "checklist_system",
        "checklist_winwin_system",
    ):
        for b in BENCHES:
            out[f"{fn}({b!r})"] = _md5(getattr(m, fn)(b))
    for b in BENCHES:
        for lg in (True, False):
            out[f"env_desc({b!r}, long={lg})"] = _md5(m.env_desc(b, long=lg))
    monkeypatch.delenv("OPSD_PI_PROMPT_ENV", raising=False)
    for e in ENVS:
        for strict in (False, True):
            try:
                s, u = m.skill_prompts(e, strict)
                out[f"skill_prompts({e!r}, strict={strict})"] = _md5(s) + ":" + _md5(u)
            except KeyError:
                out[f"skill_prompts({e!r}, strict={strict})"] = "KeyError"
    for e in ("appworld", "tau2"):
        monkeypatch.setenv("OPSD_PI_PROMPT_ENV", e)
        s, u = m.skill_prompts(None)
        out[f"skill_prompts(None) with OPSD_PI_PROMPT_ENV={e}"] = _md5(s) + ":" + _md5(u)
    monkeypatch.delenv("OPSD_PI_PROMPT_ENV", raising=False)
    for fn in ("skill_to_hint", "contrastive_to_hint", "episode_to_hint"):
        out[f"{fn}(SAMPLE)"] = _md5(getattr(m, fn)(SAMPLE))
    out["skill_update_to_hint(SAMPLE, 'p')"] = _md5(m.skill_update_to_hint(SAMPLE, "p"))
    out["checklist_to_hint(SAMPLE, max_items=1)"] = _md5(m.checklist_to_hint(SAMPLE, max_items=1))
    out["checklist_to_hint(SAMPLE)"] = _md5(m.checklist_to_hint(SAMPLE))
    return out


