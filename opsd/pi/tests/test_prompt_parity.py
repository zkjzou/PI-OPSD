"""Parity of the PI prompts and the LEGACY analyzer-input render across the merge of two development lines.

WHY THIS FILE EXISTS. ``pi/prompts.py`` was changed on both of two development lines (the ALFWorld/checklist
line and the AppWorld line), and git merged them WITHOUT conflict markers. Both sides made the analyzer
prompts environment-aware in different ways, and both families are load-bearing:

  * the ALFWorld/checklist line: templates -- ``skill_system(bench)``, ``ENV_LONG``/``ENV_SHORT``, the
    ``CHECKLIST_*`` prompts (+ ``checklist_system``/``checklist_winwin_system``/``checklist_to_hint``),
    ``CONTRASTIVE_*`` and ``SKILL_UPDATE_*`` -- which built the checklist hints;
  * the AppWorld line: hand-written ``SKILL_SYSTEM_APPWORLD``/``SKILL_SYSTEM_TAU2`` (+ users) selected by
    ``skill_prompts(env, strict)`` / ``$OPSD_PI_PROMPT_ENV`` -- which built the AppWorld/tau2 on-policy
    skill hints.

A silent auto-merge can drop or reorder a definition, and a name defined twice at module level silently
takes the LATER value. So every module-level string (and every string leaf of a module-level dict/tuple)
and every rendered prompt is pinned by md5 to the value computed from the ORIGINAL source blob it came
from. The tables below were generated by importing each original blob as a standalone module:

  OURS   = the ALFWorld/checklist line's pi/prompts.py
  THEIRS = the AppWorld line's pi/prompts.py

The 12 keys the two tables share (the ALFWorld constants and the output renderers) agree between the
blobs, and equal their common ancestor as well.

The second half pins the LEGACY analyzer-input mode (``max_input_tokens=0``): with it, every analyzer-backed
constructor must send the analyzer exactly the prompt the AppWorld-line constructor sent -- i.e.
``max_chars`` caps BOTH the analyzer input render and the hint, which is what the AppWorld runs did with
``OPSD_ONLINE_HINTS_MAX_CHARS=48000``. ``LEGACY_RENDER`` was generated by running the AppWorld-line pi
PACKAGE on the synthetic trajectories built by ``_synth`` below.

Regenerate a table ONLY if a prompt is changed on purpose -- and then say so in the commit, because any
change here changes every hint built from that prompt.

    .venv/bin/python -m pytest opsd/pi/tests/test_prompt_parity.py -q
"""

