# LEGACY analyzer-input render (max_input_tokens=0) == the AppWorld-line constructors, byte for byte.
# _synth / _cases / _REPLY are copied verbatim from the generator that produced LEGACY_RENDER.
# --------------------------------------------------------------------------------------------------
_REPLY = json.dumps(
    {
        "success_analysis": "s",
        "mistake_analysis": "m",
        "golden_workflow": ["a", "b"],
        "hint": "h",
        "episode_summary": "e",
        "episode_skill": "k",
        "updated_hint": "u",
    }
)


class _Rec:
    def __init__(self):
        self.calls = []

    async def analyze(self, prompt, **kw):
        self.calls.append({"prompt": prompt, "system": kw.get("system")})
        return _REPLY


def _synth(rep, success, n_turns=8):
    msgs = [
        {
            "role": "user",
            "content": "You are in the middle of a room.\nYour task is to: put a clean "
            f"mug in coffeemachine.\n(rollout {rep})",
        }
    ]
    for t in range(n_turns):
        think = " ".join(f"reason{rep}.{t}.{k}" for k in range(18))
        msgs.append({"role": "assistant", "content": f"<think>{think}</think>\nAction: go to shelf {t} ({rep})"})
        obs = " ".join(f"obj{rep}_{t}_{k}" for k in range(16))
        msgs.append({"role": "user", "content": f"On shelf {t}, you see {obs}."})
    return TrajView(
        task_id="t0",
        messages=msgs,
        reward=1.0 if success else 0.0,
        success=success,
        num_turns=n_turns,
        repetition_id=rep,
    )


def _cases(extra):
    win, lose, mid = _synth(0, True), _synth(1, False), _synth(2, False, n_turns=5)
    out = []
    for mc in (400, 48000):
        for st in (True, False):
            for env in ("alfworld", "appworld"):
                out.append(
                    (
                        f"onpolicy_skill mc={mc} strip={st} env={env}",
                        "onpolicy_skill",
                        dict(max_chars=mc, strip_think=st, prompt_env=env, **extra.get("onpolicy_skill", {})),
                        [win, lose],
                    )
                )
        out.append((f"contrastive mc={mc}", "contrastive", dict(max_chars=mc, **extra.get("x", {})), [win, lose]))
        for st in (True, False):
            out.append(
                (
                    f"episode_skill mc={mc} strip={st}",
                    "episode_skill",
                    dict(max_chars=mc, strip_traj_think=st, **extra.get("x", {})),
                    [lose],
                )
            )
        out.append(
            (
                f"prompt_skill mc={mc}",
                "prompt_skill",
                dict(max_chars=mc, fold_per_step=2, **extra.get("x", {})),
                [win, lose, mid],
            )
        )
        out.append(
            (
                f"reference mc={mc}",
                "reference",
                dict(max_chars=mc, mode="abstracted", **extra.get("x", {})),
                [win, lose],
            )
        )
    return out


def _run_cases(extra):
    table = {}
    for name, pt, kw, tvs in _cases(extra):
        az = _Rec()
        ctor = build_constructor(pt, az, **kw)
        loop = asyncio.new_event_loop()
        try:
            loop.run_until_complete(ctor.build_offline("t0", tvs))
        finally:
            loop.close()
        table[name] = [_md5(c["prompt"]) + ":" + _md5(c["system"] or "") for c in az.calls]
    return table


def test_synthetic_trajectory_exercises_truncation():
    """Guard the fixture: the legacy caps under test (400 chars, contrastive's 1500/side) must bite."""
    n = len(_synth(0, True).render(10**9))
    assert 1500 < n < 48000


def test_trajview_render_is_unchanged():
    for mc in (400, 1500, 48000):
        for st in (True, False):
            assert _md5(_synth(0, True).render(mc, strip_think=st)) == LEGACY_RENDER[f"render mc={mc} strip={st}"]


@pytest.mark.parametrize("legacy_value", [0, None])
def test_legacy_mode_matches_appworld_scaffold_prompts(legacy_value, monkeypatch):
    monkeypatch.delenv("OPSD_PI_PROMPT_ENV", raising=False)
    extra = {"onpolicy_skill": {"max_input_tokens": legacy_value}, "x": {"max_input_tokens": legacy_value}}
    got = _run_cases(extra)
    want = {k: v for k, v in LEGACY_RENDER.items() if not k.startswith("render ")}
    assert set(got) == set(want)
    bad = sorted(k for k in want if got[k] != want[k])
    assert bad == [], f"legacy render differs from the AppWorld-line render for: {bad}"


def test_onpolicy_skill_defaults_to_the_legacy_render(monkeypatch):
    """onpolicy_skill's DEFAULT is the AppWorld-line behaviour (no max_input_tokens passed)."""
    monkeypatch.delenv("OPSD_PI_PROMPT_ENV", raising=False)
    got = _run_cases({})
    for k, v in LEGACY_RENDER.items():
        if k.startswith("onpolicy_skill "):
            assert got[k] == v, k


def test_token_cap_mode_is_a_real_switch(monkeypatch):
    """With a positive token budget the 400-char / 1500-char legacy truncation must NOT apply."""
    monkeypatch.delenv("OPSD_PI_PROMPT_ENV", raising=False)
    got = _run_cases({"onpolicy_skill": {"max_input_tokens": 32000}, "x": {"max_input_tokens": 32000}})
    for k in (
        "onpolicy_skill mc=400 strip=True env=alfworld",
        "contrastive mc=400",
        "prompt_skill mc=400",
        "episode_skill mc=400 strip=True",
        "reference mc=400",
    ):
        assert got[k] != LEGACY_RENDER[k], f"{k}: token-cap mode rendered the legacy (truncated) input"
    # ...and at a budget large enough for the whole trajectory both modes see the full text.
    assert (
        got["onpolicy_skill mc=48000 strip=True env=alfworld"]
        == LEGACY_RENDER["onpolicy_skill mc=48000 strip=True env=alfworld"]
    )


def test_legacy_cap_to_tokens_matches_render_truncation():
    """The pre-rendered-string path (checklist's win side) uses the same chars cut in legacy mode."""
    ctor = build_constructor("static", None, max_chars=400, max_input_tokens=0)
    assert ctor.legacy_input_render
    full = _synth(0, True).render(10**9)
    assert ctor._cap_to_tokens(full, 7) == _synth(0, True).render(400)
    assert ctor._cap_to_tokens(full, legacy_max_chars=1500) == _synth(0, True).render(1500)
    assert not build_constructor("static", None).legacy_input_render
